def compute_hills_day(
    now_tehran: datetime | date | None = None,
    start_date_iso: str = DEFAULT_HILLS_START_DATE,
    tz_name: str = "Asia/Tehran",
) -> int:
    """Compute the 1-based Hills day number relative to start_date_iso in local timezone.

    2026-08-28 -> Day 1, 2026-08-29 -> Day 2, etc. Clamped to >= 1 if clock precedes start date.
    """
    start_d = date.fromisoformat(start_date_iso)
    if now_tehran is None:
        target_d = datetime.now(ZoneInfo(tz_name)).date()
    elif isinstance(now_tehran, datetime):
        tz = ZoneInfo(tz_name)
        local_dt = now_tehran.astimezone(tz) if now_tehran.tzinfo else now_tehran.replace(tzinfo=tz)
        target_d = local_dt.date()
    else:
        target_d = now_tehran

    return max(1, (target_d - start_d).days + 1)


def draw_next_greeting_index(
    deck: list[int] | None,
    last_index: int | None = None,
) -> tuple[int, list[int]]:
    """Draw the next greeting index from a persistent shuffle-bag without repeating until exhausted.

    When the deck is empty, generates a fresh shuffled permutation of all 100 templates and ensures
    the first element of the new cycle differs from last_index.
    """
    total = len(MORNING_GREETINGS)
    valid_deck: list[int] = []
    if isinstance(deck, list):
        seen: set[int] = set()
        for item in deck:
            if isinstance(item, int) and 0 <= item < total and item not in seen:
                valid_deck.append(item)
                seen.add(item)

    if not valid_deck:
        valid_deck = list(range(total))
        random.shuffle(valid_deck)
        if last_index is not None and total > 1 and valid_deck[0] == last_index:
            swap_pos = random.randrange(1, total)
            valid_deck[0], valid_deck[swap_pos] = valid_deck[swap_pos], valid_deck[0]

    chosen = valid_deck.pop(0)
    return chosen, valid_deck


